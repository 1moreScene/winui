import {cpSync,mkdirSync,existsSync,symlinkSync,readFileSync,writeFileSync} from 'node:fs';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),gallery=join(root,'gallery');
const target=join(root,'target/navigation-external-content'),sdk=join(root,'out/navigation-external-content-sdk/wasm');
const snapshot=join(root,'out/navigation-external-content-dev');
execFileSync(process.execPath,[join(root,'tools/check-control-origins.mjs'),'--check'],{cwd:root,stdio:'inherit'});
execFileSync('cargo',['build','--locked','--release','--target','wasm32-unknown-unknown','--target-dir',target],{cwd:root,stdio:'inherit'});
mkdirSync(sdk,{recursive:true});
execFileSync('wasm-bindgen',['--target','web','--out-dir',sdk,'--out-name','winui',join(target,'wasm32-unknown-unknown/release/winui_wasm.wasm')],{cwd:root,stdio:'inherit'});
const sha256=createHash('sha256').update(readFileSync(join(sdk,'winui_bg.wasm'))).digest('hex');
writeFileSync(join(sdk,'build-stamp.json'),JSON.stringify({sha256,completedAt:Date.now()}));
mkdirSync(snapshot,{recursive:true});
for(const path of ['src','public','tests','index.html','vite.config.ts','tsconfig.json','package.json'])cpSync(join(gallery,path),join(snapshot,path),{recursive:true});
cpSync(sdk,join(snapshot,'src/wasm'),{recursive:true});
if(!existsSync(join(snapshot,'node_modules')))symlinkSync(join(gallery,'node_modules'),join(snapshot,'node_modules'),'junction');
mkdirSync(join(snapshot,'references'),{recursive:true});
cpSync(join(root,'references/motion-native-defaults.json'),join(snapshot,'references/motion-native-defaults.json'));
const materials=join(snapshot,'src/MaterialsPage.tsx');
writeFileSync(materials,readFileSync(materials,'utf8').replace('../../references/motion-native-defaults.json','../references/motion-native-defaults.json'));
execFileSync(process.execPath,[join(gallery,'node_modules/vite/bin/vite.js'),'build',snapshot,'--outDir',join(root,'out/navigation-external-content-preview'),'--emptyOutDir'],{cwd:gallery,stdio:'inherit'});
console.log(`Prepared isolated navigation SDK and production build: ${sha256}`);
