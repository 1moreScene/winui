import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
const definitions = JSON.parse(readFileSync(new URL('../references/api-enums.json', import.meta.url), 'utf8'));
let ts = '// Generated by tools/generate-enums.mjs; edit references/api-enums.json.\n';
let rust = '// Generated by tools/generate-enums.mjs; edit references/api-enums.json.\nuse serde::{Deserialize,Serialize};\n';
for (const [name, definition] of Object.entries(definitions)) {
  ts += `\n/** ${definition.description} */\nexport enum ${name} {\n`;
  rust += `\n/// ${definition.description}\n#[derive(Clone,Copy,Debug,Deserialize,Serialize,PartialEq,Eq${definition.default ? ',Default' : ''})]\npub enum ${definition.rust} {\n`;
  for (const [member, [wire, doc]] of Object.entries(definition.members)) {
    ts += `  /** ${doc} */\n  ${member} = ${JSON.stringify(wire)},\n`;
    rust += `  /// ${doc}\n  #[serde(rename = ${JSON.stringify(wire)})]\n${definition.default === member ? '  #[default]\n' : ''}  ${member},\n`;
  }
  ts += '}\n'; rust += `}\nimpl ${definition.rust} { pub fn as_str(self) -> &'static str { match self {\n`;
  for (const [member, [wire]] of Object.entries(definition.members)) rust += `Self::${member} => ${JSON.stringify(wire)},\n`;
  rust += '} } }\n';
}
const formatted = spawnSync('rustfmt', ['--edition', '2021', '--emit', 'stdout'], { input: rust, encoding: 'utf8' });
if (formatted.status !== 0) throw new Error(formatted.stderr || 'rustfmt failed');
rust = formatted.stdout.replaceAll('\r\n', '\n');
for (const [path, value] of [['../src/enums.rs', rust], ['../packages/winui-wasm/src/enums.ts', ts]]) {
  const url = new URL(path, import.meta.url);
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== value) throw new Error(`${path} drifted; run node tools/generate-enums.mjs`);
  } else writeFileSync(url, value);
}
