export type PropertyValue = string | number | boolean | null | PropertyValue[] | { [key: string]: PropertyValue };
export interface PropertyField { key: string; type: 'text' | 'number' | 'boolean' | 'enum' | 'color' | 'json'; value: PropertyValue; enumName?: keyof typeof SDK; min?: number; max?: number }
const text = (key: string, value = ''): PropertyField => ({ key, type: 'text', value });
const num = (key: string, value = 0, min = 0, max = 3000): PropertyField => ({ key, type: 'number', value, min, max });
const bool = (key: string, value = false): PropertyField => ({ key, type: 'boolean', value });
const json = (key: string, value: PropertyValue): PropertyField => ({ key, type: 'json', value });
export function enumChoices(name: keyof typeof SDK): string[] {
  const source = (SDK as unknown as Record<string, unknown>)[name];
  if (!source || typeof source !== 'object') throw new Error('Unknown SDK enum: ' + name);
  return Object.values(source).filter((value): value is string => typeof value === 'string');
}
